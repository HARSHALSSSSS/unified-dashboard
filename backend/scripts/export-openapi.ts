/**
 * Writes the generated API documents (committed, so API diffs show up in code review / CI):
 *   docs/api/openapi.json   machine-readable contract (also served at /docs/openapi)
 *   docs/api/ENDPOINTS.md   human-readable endpoint catalogue grouped by Swagger tag
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { allModules } from '@oms/modules-registry';
import { buildTestApp } from '@oms/testing';

interface Op { summary: string; description?: string; tags: string[]; 'x-access'?: string; security?: unknown[] }
const t = await buildTestApp({ modules: allModules });
const spec = t.app.swagger() as unknown as { tags: Array<{ name: string; description: string }>; paths: Record<string, Record<string, Op>> };
await t.close();

const dir = resolve(import.meta.dirname, '../docs/api');
mkdirSync(dir, { recursive: true });
writeFileSync(resolve(dir, 'openapi.json'), JSON.stringify(spec, null, 2) + '\n');

const rows = new Map<string, Array<{ method: string; path: string; op: Op }>>();
for (const [path, item] of Object.entries(spec.paths)) {
  for (const [method, op] of Object.entries(item)) {
    for (const tag of op.tags) rows.set(tag, [...(rows.get(tag) ?? []), { method: method.toUpperCase(), path, op }]);
  }
}
const access = (op: Op) => (op['x-access'] === 'public' ? 'public' : op['x-access'] === 'authenticated' ? 'any signed-in user' : op['x-access'] ? `\`${op['x-access']}\`` : '-');
const md: string[] = [
  '# Endpoint catalogue',
  '',
  '> GENERATED by `pnpm openapi:export` from the route definitions. Do not edit. Live docs: `/docs`, spec: `/docs/openapi`, contract: [openapi.json](openapi.json).',
  '',
  'Access: **public** = no token · **any signed-in user** = bearer token only · `resource:action` = RBAC permission required (vendor tenant comes from the token).',
  '',
];
for (const tag of spec.tags) {
  const list = rows.get(tag.name);
  if (!list?.length) continue;
  md.push(`## ${tag.name}`, '', tag.description, '', '| Method | Path | Access | Summary |', '|---|---|---|---|');
  for (const r of list.sort((a, b) => a.path.localeCompare(b.path) || a.method.localeCompare(b.method))) md.push(`| ${r.method} | \`${r.path}\` | ${access(r.op)} | ${r.op.summary} |`);
  md.push('');
}
writeFileSync(resolve(dir, 'ENDPOINTS.md'), md.join('\n'));
console.log(`wrote openapi.json and ENDPOINTS.md (${Object.values(spec.paths).reduce((n, p) => n + Object.keys(p).length, 0)} operations)`);
